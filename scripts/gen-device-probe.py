#!/usr/bin/env python3
"""Writes testapks/composeapp/device-probe-api36.tsv from a device's run of DeviceProbeTest#probe.

One line per probed value, KEY and VALUE tab separated, sorted by KEY so a regeneration diffs cleanly. Values are
already normalised by the test (`>0`, `non-null`, `1..100`, a boolean, `EXCEPTION:ClassName`), so the table says what a
device of this API level does, not which device it was.
Generate it from a freshly booted, idle emulator on AC power with the test app freshly installed (notifications permission
untouched): `battery.charging`, `conn.defaultNetworkActive`, `notif.enabled`, `power.*` and the battery health depend on its state. Installs nothing: install the test app and its test APK first
(`adb -s SERIAL install -r app-debug.apk app-debug-androidTest.apk`) and uninstall them afterwards.

  scripts/gen-device-probe.py [-s SERIAL] [--from FILE] [-o OUT]

--from reads a saved `am instrument -r` output instead of asking adb. Keys that look like they identify a machine, a
user or a network (bssid, mac, ip, account, host...), and values that are not a class (long, or an address or a run of hex), are refused, so none gets into the repository.
"""
import argparse, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TEST = "dev.apksim.composeapp.DeviceProbeTest"
IDENTIFYING = re.compile(r"bssid|macaddr|\bmac\b|ipaddr|account|hostname|imei|iccid|phonenumber", re.I)
# Values are classes (`>0`, `ok`, a small number), never text: an address, a long string or a run of hex is refused.
SUSPECT = re.compile(r"\d+\.\d+\.\d+\.\d+|[0-9a-f]{2}(:[0-9a-f]{2}){5}|[0-9A-Fa-f]{12,}")

def parse(text):
    rows = {}
    for line in text.splitlines():
        m = re.match(r"(?:INSTRUMENTATION_STATUS: )?(probe\..+?)=(.*)$", line.rstrip("\r"))
        if m:
            rows[m.group(1)[len("probe."):]] = m.group(2)
    return rows

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-s", "--serial")
    ap.add_argument("--from", dest="src")
    ap.add_argument("-o", "--out", default=str(ROOT / "testapks/composeapp/device-probe-api36.tsv"))
    a = ap.parse_args()
    adb = ["adb"] + (["-s", a.serial] if a.serial else [])
    if a.src:
        text = pathlib.Path(a.src).read_text()
    else:
        ins = subprocess.run(adb + ["shell", "pm", "list", "instrumentation"], check=True, capture_output=True, text=True).stdout
        m = re.search(r"instrumentation:(dev\.apksim\.composeapp[^ ]*) ", ins)
        if not m:
            raise SystemExit("the test APK is not installed (pm list instrumentation shows no dev.apksim.composeapp test)")
        text = subprocess.run(adb + ["shell", "am", "instrument", "-w", "-r", "-e", "class", TEST, m.group(1)],
                              check=True, capture_output=True, text=True).stdout
    rows = parse(text)
    if len(rows) < 100:
        raise SystemExit("only %d probe values: did the test run? output tail:\n%s" % (len(rows), text[-1500:]))
    bad = [k for k, v in rows.items() if IDENTIFYING.search(k) or len(v) > 60 or SUSPECT.search(v)]
    if bad:
        raise SystemExit("keys that may identify a machine or user: %s" % ", ".join(bad))
    out = pathlib.Path(a.out)
    with out.open("w") as f:
        f.write("# KEY\tVALUE. Generated by scripts/gen-device-probe.py from DeviceProbeTest#probe on an API 36 emulator; do not edit.\n")
        for k in sorted(rows):
            f.write("%s\t%s\n" % (k, rows[k]))
    print("%s: %d values" % (out, len(rows)))

main()
