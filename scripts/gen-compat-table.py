#!/usr/bin/env python3
"""Writes runtime/src/main/resources/dev/apksim/compat-table.tsv from a device's `dumpsys platform_compat`.

One line per compat change: ID, NAME, SINCE, FLAGS, tab separated, sorted by ID so a regeneration diffs cleanly.
SINCE is enableSinceTargetSdk (0 when the change has none: enabled for every app unless FLAGS says otherwise);
FLAGS is `disabled` (off unless an override turns it on: off here), `logging` (loggingOnly: on) or `-`.
Per-package overrides are ignored. The table is what a device with this build answers for an app with no override.

  scripts/gen-compat-table.py [-s SERIAL] [--from FILE] [-o OUT]
"""
import argparse, re, subprocess, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
LINE = re.compile(r"ChangeId\((\d+); name=([^;)]+)((?:; [^;]*?)*)\)$")

def parse(text):
    rows = {}
    for raw in text.splitlines():
        raw = raw.strip()
        if not raw.startswith("ChangeId("):
            continue
        # Drop the override maps first: package names there may contain ';'-free text but are long.
        flat = re.sub(r"; (?:packageOverrides|rawOverrides)=\{[^}]*\}", "", raw)
        m = LINE.match(flat)
        if not m:
            raise SystemExit("cannot parse: " + raw[:200])
        cid, name, rest = int(m.group(1)), m.group(2), m.group(3)
        since, flag = 0, "-"
        for part in [p.strip() for p in rest.split(";") if p.strip()]:
            if part.startswith("enableSinceTargetSdk="):
                since = int(part.split("=")[1])
            elif part == "disabled":
                flag = "disabled"
            elif part == "loggingOnly":
                flag = "logging"
            elif part == "overridable":
                pass
            else:
                raise SystemExit("unknown attribute %r in: %s" % (part, flat))
        rows[cid] = (name, since, flag)
    return rows

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-s", "--serial")
    ap.add_argument("--from", dest="src", help="read a saved dumpsys instead of asking adb")
    ap.add_argument("-o", "--out", default=str(ROOT / "runtime/src/main/resources/dev/apksim/compat-table.tsv"))
    a = ap.parse_args()
    if a.src:
        text = pathlib.Path(a.src).read_text()
    else:
        cmd = ["adb"] + (["-s", a.serial] if a.serial else []) + ["shell", "dumpsys", "platform_compat"]
        text = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    rows = parse(text)
    if len(rows) < 100:
        raise SystemExit("only %d changes: not a platform_compat dump?" % len(rows))
    out = pathlib.Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as f:
        f.write("# id\tname\tenableSinceTargetSdk\tflags. Generated by scripts/gen-compat-table.py; do not edit.\n")
        for cid in sorted(rows):
            n, s, fl = rows[cid]
            f.write("%d\t%s\t%d\t%s\n" % (cid, n, s, fl))
    print("%s: %d changes" % (out, len(rows)))

main()
